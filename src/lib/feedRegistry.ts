// Every feed the app reads, one entry per row of the Live feeds table in
// docs/data-sources.md, plus the news monitor's snapshot. The /status page and
// its health checks (src/status/) read this list; nothing else lists feeds.

/** How the browser gets the feed: straight from the publisher, through one of the app's proxies, or from the app's own server. */
export type ReadPath = 'direct' | 'proxy' | 'server'

export interface Feed {
  id: string
  name: string
  publisher: string
  /** The publisher's address, as docs/data-sources.md writes it. */
  url: string
  /** The app path a proxied or server-read feed is read through, or null when the browser reads `url` itself. */
  path: string | null
  licence: string
  read: ReadPath
  /** How often the app re-reads it while something needs it, in seconds; null when it is read once per visit or on demand. */
  refreshSeconds: number | null
  /** When the feed is read, in the docs' words, where the number alone doesn't say. */
  refreshNote: string | null
  /** The layers, pages or screens the feed shows up on. */
  feeds: string[]
  /** The module that fetches and parses it. */
  module: string
  /** The publisher's page for the dataset, or null when the docs give none. */
  datasetUrl: string | null
}

